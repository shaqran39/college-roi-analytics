"""Does College Pay Off? Streamlit dashboard on the Databricks marts.

Run locally from the project root:  streamlit run dashboards/app.py
"""

import streamlit as st

from db import REPO_URL, data_updated, refresh_button

st.set_page_config(page_title="Does College Pay Off?", page_icon="🎓", layout="wide")

# Streamlit's captions are quite small by default; make them easier to read on laptops and phones
st.html("<style>[data-testid='stCaptionContainer'] { font-size: 0.95rem; }</style>")

auto_insights = st.Page("views/auto_insights.py", title="Auto insights", icon=":material/auto_awesome:")
page = st.navigation([
    st.Page("views/overview.py", title="Overview", icon=":material/insights:", default=True),
    st.Page("views/majors.py", title="Majors", icon=":material/school:"),
    st.Page("views/colleges_and_choices.py", title="Colleges & choices", icon=":material/account_balance:"),
    st.Page("views/deep_dive.py", title="Deep dive", icon=":material/query_stats:"),
    auto_insights,
])

with st.sidebar:
    st.markdown("**Does College Pay Off?**")
    st.caption("An end-to-end analytics project: 30,000 synthetic graduates through Databricks, dbt and AI, "
               "plus an automatic profiler for any CSV.")
    st.page_link(auto_insights, label="Profile your own CSV", icon=":material/upload_file:")
    st.page_link(REPO_URL, label="Source code on GitHub", icon=":material/code:")
    refresh_button()
    updated = data_updated()
    if updated:
        st.caption(f":material/update: College data updated {updated}")

page.run()

st.divider()
st.caption(
    "**Synthetic data:** simulated graduates, not real people. Results describe this dataset only "
    f"and are not financial advice. AI-written text is generated by Databricks `ai_query` from the numbers shown. "
    f"[Source code]({REPO_URL})"
)
